#!/usr/bin/env python3
"""Generates cases/tables_churn.json, for examples/lucidcc/tables_churn.dpt.

The case fills and empties a 32-entry exact table. Its keys are chosen to 
collide in lucidcc's hash table (64 slots for 32 entries; the hash is 
table_hash_mix in CCoreTables.ml), including a run of entries that wraps 
around the end of the slots. Removes then happen in the middle of runs, 
which is the case that a hash table with open addressing has to get right.

The expected outputs come from a model of the table (a dict with at most 
32 entries), not from lucidcc.

Usage: gen_tables_churn.py > cases/tables_churn.json
"""
import json
import random

SIZE, SLOTS = 32, 64
M64 = (1 << 64) - 1


def home(key):
    """the key's home slot in lucidcc's table"""
    h = key
    h ^= h >> 33
    h = (h * 0xff51afd7ed558ccd) & M64
    h ^= h >> 33
    h = (h * 0xc4ceb9fe1a85ec53) & M64
    h ^= h >> 33
    return h & (SLOTS - 1)


def keys_at(slot, n):
    """the first n keys whose home is slot"""
    found, key = [], 1
    while len(found) < n:
        if home(key) == slot:
            found.append(key)
        key += 1
    return found


def main():
    rng = random.Random(1)
    # colliding groups: 12 keys at slot 5, 8 at slot 6, 6 at slot 7 (one long run), 
    # 8 at slot 62 (a run that wraps around), and 6 more at slot 30
    keys = keys_at(5, 12) + keys_at(6, 8) + keys_at(7, 6) + keys_at(62, 8) + keys_at(30, 6)
    table, events, expected = {}, [], []

    def event(name, args):
        events.append({"name": name, "args": args, "locations": ["0:1"], "timestamp": len(events) * 1000000})

    def install(key, val):
        event("do_install", [key, val])
        if key not in table and len(table) < SIZE:
            table[key] = val

    def remove(key):
        event("do_remove", [key])
        table.pop(key, None)

    def query(key):
        event("do_query", [key])
        val, hit = (table[key], 1) if key in table else (1000, 0)
        expected.append({"name": "query_result", "args": [key, val, hit]})

    def query_all():
        for key in keys:
            query(key)

    # fill the table, in a mixed order (the last 8 installs are rejected)
    order = keys[:]
    rng.shuffle(order)
    for key in order:
        install(key, key % 1000)
    query_all()
    # remove every other key of each group: holes in the middle of the runs
    for key in keys[::2]:
        remove(key)
    query_all()
    # churn: random installs and removes
    for i in range(120):
        key = rng.choice(keys)
        if rng.random() < 0.5:
            install(key, 2000 + i)
        else:
            remove(key)
    query_all()
    # empty the table
    for key in order:
        remove(key)
    query_all()

    lines = ",\n".join("    " + json.dumps(e) for e in events)
    exp = ",\n".join("      " + json.dumps(e) for e in expected)
    comment = ("Generated by test/ltf/gen_tables_churn.py. Fills and empties a 32-entry exact table with keys "
               "that collide in lucidcc's hash table: installs (some into the full table), removes from the "
               "middle of runs of colliding entries, random installs and removes, then removes of every key. "
               "Every key is queried after each phase.")
    print('{\n  "comment": %s,\n  "max time": %d,\n'
          '  "topology": {"nodes": {"0": {"ports": {"196": {"type": "recirc"}}}}, "links": []},\n'
          '  "events": [\n%s\n  ],\n  "expected": {\n    "1": [\n%s\n    ]\n  }\n}'
          % (json.dumps(comment), (len(events) + 5) * 1000000, lines, exp))


if __name__ == "__main__":
    main()
